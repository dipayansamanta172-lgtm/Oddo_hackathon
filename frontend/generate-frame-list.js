import fs from 'fs';
import path from 'path';

const dirPath = path.resolve('Landingpage');
const outputPath = path.resolve('src/components/frameList.js');

try {
  const files = fs.readdirSync(dirPath)
    .filter(file => file.endsWith('.jpg') || file.endsWith('.jpeg') || file.endsWith('.png'))
    .sort();

  const filePaths = files.map(file => `/Landingpage/${file}`);

  const content = `// This file is auto-generated by generate-frame-list.js
export const frames = ${JSON.stringify(filePaths, null, 2)};
`;

  fs.writeFileSync(outputPath, content);
  console.log(`Successfully generated frame list with ${files.length} frames at ${outputPath}`);
} catch (err) {
  console.error('Error generating frame list:', err);
}
